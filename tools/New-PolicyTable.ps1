<#
.SYNOPSIS
    Regenerates docs\POLICIES.md from the catalog and a real policy file.

.DESCRIPTION
    The table is generated rather than written by hand because v1 shipped a feature
    table with a row stated backwards -- it claimed Edge was required for web search
    where the policy says the opposite. A generated table cannot disagree with the
    code.

    The classification (Benefit / Loss / Choice) comes from Catalog.cs. The global
    and EU states come from the policy file, so the output names the Windows build
    it was read from; another build may differ.

.PARAMETER PolicyFile
    The policy file to read states from. Defaults to this machine's.

.PARAMETER OutFile
    Where to write the table. Defaults to docs\POLICIES.md.
#>
[CmdletBinding()]
param(
    [string]$PolicyFile = (Join-Path $env:SystemRoot 'System32\IntegratedServicesRegionPolicySet.json'),
    [string]$OutFile,
    [string]$Iso2 = 'IE'
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not $OutFile) { $OutFile = Join-Path $repoRoot 'docs\POLICIES.md' }

$catalogFile = Join-Path $repoRoot 'src\EULord\Core\Catalog.cs'
$catalogText = [IO.File]::ReadAllText($catalogFile, [Text.Encoding]::UTF8)

# Mirrors the C# literal: E("{guid}", "Id", C.Class, "tw", "cn", "en")
$pattern = 'E\("(\{[0-9a-fA-F-]{36}\})",\s*"([A-Za-z0-9]+)",\s*C\.(Benefit|Loss|Choice),\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"\)'
$entries = foreach ($m in [regex]::Matches($catalogText, $pattern)) {
    [pscustomobject]@{
        Guid  = $m.Groups[1].Value
        Id    = $m.Groups[2].Value
        Class = $m.Groups[3].Value
        Tw    = $m.Groups[4].Value -replace '\\"', '"'
        Cn    = $m.Groups[5].Value -replace '\\"', '"'
        En    = $m.Groups[6].Value -replace '\\"', '"'
    }
}
if ($entries.Count -eq 0) { throw "No catalog entries parsed from $catalogFile" }

$policy = Get-Content -LiteralPath $PolicyFile -Raw -Encoding UTF8 | ConvertFrom-Json
$states = @{}
foreach ($entry in $policy.policies) {
    $guid = ([string]$entry.guid).ToLowerInvariant()
    if ($states.ContainsKey($guid)) { continue }

    $eea = $entry.defaultState
    if ($entry.PSObject.Properties.Name -contains 'conditions' -and $entry.conditions -and
        $entry.conditions.PSObject.Properties.Name -contains 'region' -and $entry.conditions.region) {
        $region = $entry.conditions.region
        if ($region.PSObject.Properties.Name -contains 'enabled' -and $region.enabled -contains $Iso2) { $eea = 'enabled' }
        elseif ($region.PSObject.Properties.Name -contains 'disabled' -and $region.disabled -contains $Iso2) { $eea = 'disabled' }
    }
    $states[$guid] = [pscustomobject]@{ Global = $entry.defaultState; Eea = $eea }
}

$build = [Environment]::OSVersion.Version.ToString()
$today = (Get-Date).ToString('yyyy-MM-dd', [Globalization.CultureInfo]::InvariantCulture)

function Get-Mark {
    param([string]$State)
    if ($State -eq 'enabled') { return 'on' }
    if ($State -eq 'disabled') { return 'off' }
    return '?'
}

$sb = New-Object Text.StringBuilder
$null = $sb.AppendLine('# 策略對照表 · 策略对照表 · Policy table')
$null = $sb.AppendLine()
$null = $sb.AppendLine('<!-- Generated by tools\New-PolicyTable.ps1. Do not edit by hand. -->')
$null = $sb.AppendLine()
$null = $sb.AppendLine("Generated $today from Windows $build, reading the policy file for ``$Iso2``.")
$null = $sb.AppendLine('Another Windows build may ship different states, and Microsoft adds policies over time.')
$null = $sb.AppendLine()
$null = $sb.AppendLine('**Class** is the classification in `src/EULord/Core/Catalog.cs`, and it decides what the superset does:')
$null = $sb.AppendLine()
$null = $sb.AppendLine('| Class | 中文 | What the superset does |')
$null = $sb.AppendLine('|---|---|---|')
$null = $sb.AppendLine('| Gain | 好處 / 好处 | Takes the EU state. |')
$null = $sb.AppendLine('| Loss | 損失 / 损失 | **Refuses** the EU state and keeps Windows'' own. |')
$null = $sb.AppendLine('| Taste | 見仁見智 / 见仁见智 | Keeps Windows'' own state unless you tick it. |')
$null = $sb.AppendLine()
$null = $sb.AppendLine('**Description** says what the policy does when it is *enabled*, not what we set it to.')
$null = $sb.AppendLine('**Global** and **EU** are the states Windows itself would use outside and inside the EEA.')
$null = $sb.AppendLine('**Result** is what this tool writes with nothing ticked.')
$null = $sb.AppendLine()

foreach ($class in 'Benefit', 'Loss', 'Choice') {
    $group = @($entries | Where-Object { $_.Class -eq $class })
    $heading = switch ($class) {
        'Benefit' { "好處 · 好处 · Gains ($($group.Count))" }
        'Loss'    { "損失 · 损失 · Losses ($($group.Count))" }
        default   { "見仁見智 · 见仁见智 · Matters of taste ($($group.Count))" }
    }
    $null = $sb.AppendLine("## $heading")
    $null = $sb.AppendLine()

    switch ($class) {
        'Benefit' { $null = $sb.AppendLine('The EU state is an improvement, so the superset takes it. Nothing here is optional.') }
        'Loss'    { $null = $sb.AppendLine('The EU build **removes** these. The superset keeps Windows'' own behaviour, so you lose nothing. You can still take the EU state for any of them in the advanced table.') }
        default   { $null = $sb.AppendLine('Neither a gain nor a loss. Off by default; tick the ones you want in the window, or pass `--choice <Id>`.') }
    }
    $null = $sb.AppendLine()
    $null = $sb.AppendLine('| Id | 繁體中文 | 简体中文 | English | Global | EU | Result |')
    $null = $sb.AppendLine('|---|---|---|---|---|---|---|')

    foreach ($entry in $group) {
        $state = $states[$entry.Guid.ToLowerInvariant()]
        $global = if ($state) { Get-Mark $state.Global } else { '—' }
        $eea = if ($state) { Get-Mark $state.Eea } else { '—' }
        $result = if (-not $state) { '—' }
                  elseif ($entry.Class -eq 'Benefit') { "**$eea**" }
                  else { $global }

        $null = $sb.AppendLine(('| `{0}` | {1} | {2} | {3} | {4} | {5} | {6} |' -f
            $entry.Id, $entry.Tw, $entry.Cn, $entry.En, $global, $eea, $result))
    }
    $null = $sb.AppendLine()
}

$null = $sb.AppendLine('## GUIDs')
$null = $sb.AppendLine()
$null = $sb.AppendLine('| Id | GUID |')
$null = $sb.AppendLine('|---|---|')
foreach ($entry in $entries) {
    $null = $sb.AppendLine(('| `{0}` | `{1}` |' -f $entry.Id, $entry.Guid))
}

New-Item -ItemType Directory -Force -Path (Split-Path -Parent $OutFile) | Out-Null
[IO.File]::WriteAllText($OutFile, ($sb.ToString() -replace "`r`n", "`n"), (New-Object Text.UTF8Encoding($false)))

Write-Host ("wrote    {0}" -f $OutFile)
Write-Host ("entries  {0} ({1} gains, {2} losses, {3} matters of taste)" -f
    $entries.Count,
    @($entries | Where-Object Class -eq 'Benefit').Count,
    @($entries | Where-Object Class -eq 'Loss').Count,
    @($entries | Where-Object Class -eq 'Choice').Count)
