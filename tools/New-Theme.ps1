<#
.SYNOPSIS
    Generates src\EULord\Ui\Theme.cs from design\tokens.json.

.DESCRIPTION
    The design system and the product read the same numbers, so a colour can never
    drift between the mockup and the window. Edit design\tokens.json, run this,
    commit both.

    design\tokens.json is a copy of the EU Lord design system's tokens.json, kept
    in the repository so a build needs nothing but this checkout.

    Check-Theme.ps1 runs this to a temporary file in CI and fails if the committed
    Theme.cs differs, which is what stops someone hand-editing one and not the other.

.PARAMETER OutFile
    Where to write. Defaults to src\EULord\Ui\Theme.cs.
#>
[CmdletBinding()]
param([string]$OutFile)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$repoRoot = Split-Path -Parent $PSScriptRoot
$tokensPath = Join-Path $repoRoot 'design\tokens.json'
if (-not $OutFile) { $OutFile = Join-Path $repoRoot 'src\EULord\Ui\Theme.cs' }

$tokens = Get-Content -LiteralPath $tokensPath -Raw -Encoding UTF8 | ConvertFrom-Json

# --- names ------------------------------------------------------------------
# ground-ink -> GroundInk, plane-1 -> Plane1, red -> Red
function ConvertTo-PascalCase {
    param([Parameter(Mandatory)][string]$Name)
    return (($Name -split '[-_.]' | Where-Object { $_ } | ForEach-Object {
        $_.Substring(0, 1).ToUpperInvariant() + $_.Substring(1)
    }) -join '')
}

# #RRGGBB or #AARRGGBB -> the four bytes WPF wants.
function ConvertFrom-HexColor {
    param([Parameter(Mandatory)][string]$Hex)
    $h = $Hex.TrimStart('#')
    if ($h.Length -eq 6) { $h = 'FF' + $h }
    if ($h.Length -ne 8) { throw "Not a colour this generator understands: $Hex" }
    return [pscustomobject]@{
        A = [Convert]::ToByte($h.Substring(0, 2), 16)
        R = [Convert]::ToByte($h.Substring(2, 2), 16)
        G = [Convert]::ToByte($h.Substring(4, 2), 16)
        B = [Convert]::ToByte($h.Substring(6, 2), 16)
    }
}

function Get-Px {
    param([Parameter(Mandatory)][string]$Value)
    return [double]($Value -replace 'px$', '')
}

function Get-Ms {
    param([Parameter(Mandatory)][string]$Value)
    return [int]($Value -replace 'ms$', '')
}

# Every token becomes a member of one static class, so a name used twice in two
# families is a compile error in generated code rather than a clear message here.
$seen = @{}
foreach ($family in 'color', 'spacing', 'radius', 'size', 'motion') {
    if (-not $tokens.PSObject.Properties.Name.Contains($family)) { continue }
    foreach ($t in $tokens.$family.tokens) {
        $member = ConvertTo-PascalCase $t.name
        if ($seen.ContainsKey($member)) {
            throw "Token '$($t.name)' in $family collides with '$($seen[$member])': both become Theme.$member. Rename one."
        }
        $seen[$member] = "$family/$($t.name)"
    }
}

$sb = New-Object Text.StringBuilder
function Line { param([string]$Text = '') { } }
$add = { param([string]$Text = '') $null = $sb.AppendLine($Text) }

& $add '// Design tokens. GENERATED by tools\New-Theme.ps1 from design\tokens.json.'
& $add '//'
& $add '// Do not edit by hand: CI regenerates this and fails if it differs, so a change'
& $add '// made here and not in the design system would be reverted anyway. Edit'
& $add '// design\tokens.json instead, run the generator, and commit both.'
& $add '//'
& $add '// The style is Swiss International Typographic: a 12-column grid, flush-left'
& $add '// ragged-right text, square corners everywhere, no blurred shadows, hierarchy'
& $add '// from size and weight, and one accent -- iron-oxide red -- used once per view.'
& $add '// Depth comes from flat colour planes overlapping on the grid, which is why'
& $add '// Plane2 inverts between themes: the upper plane has to keep reading as the'
& $add '// upper plane in both.'
& $add ''
& $add 'using System;'
& $add 'using System.Windows;'
& $add 'using System.Windows.Media;'
& $add ''
& $add 'namespace EULord.Ui'
& $add '{'
& $add '    /// <summary>Which palette the window is painted with.</summary>'
& $add '    internal enum ThemeMode { Light, Dark }'
& $add ''
& $add '    internal static class Theme'
& $add '    {'
& $add '        private static ThemeMode _mode = ThemeMode.Light;'
& $add ''
& $add '        /// <summary>Raised after Mode changes, so open windows can repaint.</summary>'
& $add '        public static event EventHandler Changed;'
& $add ''
& $add '        public static ThemeMode Mode'
& $add '        {'
& $add '            get { return _mode; }'
& $add '            set'
& $add '            {'
& $add '                if (_mode == value) return;'
& $add '                _mode = value;'
& $add '                EventHandler handler = Changed;'
& $add '                if (handler != null) handler(null, EventArgs.Empty);'
& $add '            }'
& $add '        }'
& $add ''
& $add '        public static bool IsDark { get { return _mode == ThemeMode.Dark; } }'
& $add ''
& $add '        private static Brush Pick(uint light, uint dark)'
& $add '        {'
& $add '            return _mode == ThemeMode.Dark ? Frozen(dark) : Frozen(light);'
& $add '        }'
& $add ''
& $add '        private static readonly System.Collections.Generic.Dictionary<uint, Brush> _brushes ='
& $add '            new System.Collections.Generic.Dictionary<uint, Brush>();'
& $add ''
& $add '        /// <summary>One frozen brush per colour, so repainting allocates nothing.</summary>'
& $add '        private static Brush Frozen(uint argb)'
& $add '        {'
& $add '            Brush brush;'
& $add '            if (_brushes.TryGetValue(argb, out brush)) return brush;'
& $add ''
& $add '            var solid = new SolidColorBrush(Color.FromArgb('
& $add '                (byte)((argb >> 24) & 0xFF), (byte)((argb >> 16) & 0xFF),'
& $add '                (byte)((argb >> 8) & 0xFF), (byte)(argb & 0xFF)));'
& $add '            solid.Freeze();'
& $add '            _brushes[argb] = solid;'
& $add '            return solid;'
& $add '        }'
& $add ''
& $add '        // -- colour ----------------------------------------------------------'
& $add ''

foreach ($t in $tokens.color.tokens) {
    $name = ConvertTo-PascalCase $t.name
    $l = ConvertFrom-HexColor $t.value.light
    $d = ConvertFrom-HexColor $t.value.dark
    $lv = '0x{0:X2}{1:X2}{2:X2}{3:X2}' -f $l.A, $l.R, $l.G, $l.B
    $dv = '0x{0:X2}{1:X2}{2:X2}{3:X2}' -f $d.A, $d.R, $d.G, $d.B
    & $add ("        /// <summary>{0}</summary>" -f ($t.usage -replace '<', '&lt;' -replace '>', '&gt;'))
    & $add ("        public static Brush {0} {{ get {{ return Pick({1}u, {2}u); }} }}" -f $name, $lv, $dv)
    & $add ''
}

& $add '        // -- type ------------------------------------------------------------'
& $add ''
foreach ($key in $tokens.type.families.PSObject.Properties.Name) {
    $name = ConvertTo-PascalCase $key
    & $add ("        public const string {0}Family = ""{1}"";" -f $name, $tokens.type.families.$key)
}
& $add ''

foreach ($group in $tokens.type.groups) {
    foreach ($style in $group.styles) {
        $name = ConvertTo-PascalCase $style.name
        & $add ("        public const double {0}Size = {1};" -f $name, (Get-Px $style.fontSize))
        & $add ("        public const double {0}Line = {1};" -f $name, (Get-Px $style.lineHeight))
        & $add ("        public const int {0}Weight = {1};" -f $name, $style.fontWeight)
        if ($style.PSObject.Properties.Name -contains 'letterSpacing') {
            # WPF measures tracking in 1/1000 em, CSS in em.
            $em = [double]($style.letterSpacing -replace 'em$', '')
            & $add ("        public const int {0}Tracking = {1};" -f $name, [int][Math]::Round($em * 1000))
        }
        & $add ''
    }
}

foreach ($family in 'spacing', 'radius', 'size') {
    & $add ("        // -- {0} " -f $family) + ('-' * (66 - $family.Length))
    & $add ''
    foreach ($t in $tokens.$family.tokens) {
        $name = ConvertTo-PascalCase $t.name
        & $add ("        /// <summary>{0}</summary>" -f ($t.usage -replace '<', '&lt;' -replace '>', '&gt;'))
        & $add ("        public const double {0} = {1};" -f $name, (Get-Px $t.value))
        & $add ''
    }
}

& $add '        // -- motion ----------------------------------------------------------'
& $add ''
foreach ($t in $tokens.motion.tokens) {
    $name = ConvertTo-PascalCase $t.name
    & $add ("        /// <summary>{0}</summary>" -f ($t.usage -replace '<', '&lt;' -replace '>', '&gt;'))
    & $add ("        public static readonly Duration {0} = new Duration(TimeSpan.FromMilliseconds({1}));" -f $name, (Get-Ms $t.value))
    & $add ''
}

& $add '        /// <summary>'
& $add '        /// The one easing curve in the product: symmetric, mechanical, no overshoot.'
& $add '        /// This is a tool reporting what it did, not an app being charming.'
& $add '        /// </summary>'
& $add '        public static System.Windows.Media.Animation.IEasingFunction Mech()'
& $add '        {'
& $add '            var ease = new System.Windows.Media.Animation.CubicEase'
& $add '            {'
& $add '                EasingMode = System.Windows.Media.Animation.EasingMode.EaseInOut'
& $add '            };'
& $add '            return ease;'
& $add '        }'
& $add ''
& $add '        /// <summary>True when the viewer asked Windows for less motion.</summary>'
& $add '        public static bool ReduceMotion'
& $add '        {'
& $add '            get'
& $add '            {'
& $add '                try { return !SystemParameters.ClientAreaAnimation; }'
& $add '                catch (Exception) { return false; }'
& $add '            }'
& $add '        }'
& $add '    }'
& $add '}'

New-Item -ItemType Directory -Force -Path (Split-Path -Parent $OutFile) | Out-Null
$text = ($sb.ToString() -replace "`r`n", "`n") -replace "`n", "`r`n"
[IO.File]::WriteAllText($OutFile, $text, (New-Object Text.UTF8Encoding($true)))

Write-Host ("wrote    {0}" -f $OutFile)
Write-Host ("colours  {0}" -f $tokens.color.tokens.Count)
Write-Host ("sizes    {0} spacing, {1} size, {2} motion" -f
    $tokens.spacing.tokens.Count, $tokens.size.tokens.Count, $tokens.motion.tokens.Count)
